// Неон в светлой теме.
//
// Захар: «только на белом нигде нет неонового глоу эффекта». Так и есть:
// когда сайт переводили на светлую тему, фиолетовые свечения заменили
// серыми тенями — и фирменная подсветка осталась только в «нашем режиме».
//
// Почему нельзя просто скопировать тёмные значения. В тёмной теме гало
// радиусом 130 px при прозрачности .8 читается как СВЕТ: оно светлее фона.
// На белом светлее фона уже некуда, и та же тень выходит серой грязью.
// Рабочая настройка для белого — радиус вдвое меньше, цвет плотнее и
// тонкое фиолетовое кольцо в 1 px, которое держит край.
//
// Галерея настроена отдельно, в galeria-buduj.mjs.

import { readFileSync, writeFileSync } from 'node:fs';

const PLIK = 'index.html';
let h = readFileSync(PLIK, 'utf8');

const style = `
<style data-neon-jasny>
  /* Лента рилсов на первом экране: в тёмной теме карточки светятся
     фиолетовым, в светлой были серыми. */
  html.jasny #hero .pg-karta {
    background: #eceaf0;
    box-shadow:
      0 0 0 1px rgba(124,58,237,.26),
      0 10px 28px rgba(124,58,237,.28),
      0 0 46px rgba(139,92,246,.32);
  }
  html.jasny #hero .pg-karta:hover {
    box-shadow:
      0 0 0 1px rgba(124,58,237,.45),
      0 16px 40px rgba(124,58,237,.34),
      0 0 70px rgba(139,92,246,.42);
  }
</style>
`;
if (!h.includes('<style data-neon-jasny>')) {
  h = h.replace('</head>', style + '</head>');
  writeFileSync(PLIK, h);
  console.log('неон в светлой теме добавлен');
} else {
  console.log('нечего менять');
}
